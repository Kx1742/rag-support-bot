const lang = pickLanguage();

function pickLanguage() {
  const fromUrl = new URLSearchParams(location.search).get("lang");
  if (fromUrl && STRINGS[fromUrl]) return fromUrl;
  try {
    const saved = localStorage.getItem("lang");
    if (saved && STRINGS[saved]) return saved;
  } catch {
    /* storage blocked */
  }
  for (const l of navigator.languages ?? [navigator.language]) {
    const code = String(l).toLowerCase();
    if (code.startsWith("zh")) return "zh";
    if (code.startsWith("ms")) return "ms";
    if (code.startsWith("en")) return "en";
  }
  return "en";
}

/** Translates a key, filling {placeholders}. Falls back to English, then to the key itself. */
function t(key, vars = {}) {
  const text = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}

function peopleLabel(n) {
  return n === 1 ? t("onePerson") : t("nPeople", { n });
}

/** Saves the choice and reloads the page in that language. */
function setLanguage(code) {
  try {
    localStorage.setItem("lang", code);
  } catch {
    /* storage blocked: the choice lasts until the page is closed */
  }
  const url = new URL(location.href);
  url.searchParams.delete("lang");
  location.replace(url);
}

/** Translates static HTML: data-i18n (text), data-i18n-placeholder, data-i18n-aria, data-i18n-title. */
function translatePage() {
  document.documentElement.lang = lang === "zh" ? "zh-Hans" : lang;
  for (const el of document.querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll("[data-i18n-placeholder]")) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll("[data-i18n-aria]")) el.setAttribute("aria-label", t(el.dataset.i18nAria));
  for (const el of document.querySelectorAll("[data-i18n-title]")) el.title = t(el.dataset.i18nTitle);
}

